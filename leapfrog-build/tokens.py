#!/usr/bin/env python3
"""Design tokens: CSS variables, Tailwind theme, WCAG contrast. Standard library only.

    tokens.py all leapfrog/design/tokens.json --out src/styles   # css + tailwind + contrast
    tokens.py contrast leapfrog/design/tokens.json               # exit 1 on any AA failure

tokens.json shape (template: templates/tokens.json):
    color   {role: "#hex"}           text   {name: [size_px, line_height_px, weight?]}
    font    {sans: "...", mono: ...} space  {base: 4, scale: [0, 4, 8, ...]}
    radius  {name: px}               shadow {name: "css shadow"}
    pairs   [[fg_role, bg_role, "body" | "large" | "ui"], ...]
AA needs 4.5:1 for body text, 3:1 for large text and UI parts (borders, focus).
"""

import argparse
import json
import os
import re
import sys

NEED = {"body": 4.5, "large": 3.0, "ui": 3.0}


def parse_color(s):
    s = s.strip().lower()
    m = re.fullmatch(r"#([0-9a-f]{3,8})", s)
    if m:
        h = m.group(1)
        if len(h) in (3, 4):
            h = "".join(c * 2 for c in h)
        if len(h) not in (6, 8):
            raise ValueError("bad colour %r" % s)
        return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))
    m = re.fullmatch(r"rgba?\(\s*(\d+)[ ,]+(\d+)[ ,]+(\d+)(?:\s*[,/]\s*[\d.]+%?)?\s*\)", s)
    if m:
        return tuple(int(x) for x in m.groups())
    raise ValueError("bad colour %r" % s)


def luminance(rgb):
    def ch(c):
        c = c / 255.0
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (ch(c) for c in rgb)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def ratio(fg, bg):
    a, b = luminance(parse_color(fg)), luminance(parse_color(bg))
    hi, lo = max(a, b), min(a, b)
    return (hi + 0.05) / (lo + 0.05)


def contrast(tokens):
    colors = tokens.get("color", {})
    results = []
    for p in tokens.get("pairs", []):
        fg, bg = p[0], p[1]
        kind = p[2] if len(p) > 2 else "body"
        if fg not in colors or bg not in colors:
            results.append((fg, bg, kind, None, "missing role"))
            continue
        r = ratio(colors[fg], colors[bg])
        results.append((fg, bg, kind, r, "ok" if r >= NEED.get(kind, 4.5) else "FAIL"))
    return results


def to_css(tokens):
    lines = [":root {"]
    for role, v in tokens.get("color", {}).items():
        lines.append("  --color-%s: %s;" % (role, v))
    for name, v in tokens.get("font", {}).items():
        lines.append("  --font-%s: %s;" % (name, v))
    for name, v in tokens.get("text", {}).items():
        lines.append("  --text-%s: %spx;" % (name, v[0]))
        if len(v) > 1:
            lines.append("  --leading-%s: %spx;" % (name, v[1]))
    for i, v in enumerate(tokens.get("space", {}).get("scale", [])):
        lines.append("  --space-%d: %spx;" % (i, v))
    for name, v in tokens.get("radius", {}).items():
        lines.append("  --radius-%s: %spx;" % (name, v))
    for name, v in tokens.get("shadow", {}).items():
        lines.append("  --shadow-%s: %s;" % (name, v))
    lines.append("}")
    dark = tokens.get("dark", {}).get("color")
    if dark:
        lines += ["", "@media (prefers-color-scheme: dark) {", "  :root {"]
        lines += ["    --color-%s: %s;" % kv for kv in dark.items()]
        lines += ["  }", "}"]
    return "\n".join(lines) + "\n"


def to_tailwind(tokens):
    theme = {
        "colors": {r: "var(--color-%s)" % r for r in tokens.get("color", {})},
        "fontFamily": {n: "var(--font-%s)" % n for n in tokens.get("font", {})},
        "fontSize": {n: ["var(--text-%s)" % n, {"lineHeight": "var(--leading-%s)" % n}] if len(v) > 1
                     else "var(--text-%s)" % n for n, v in tokens.get("text", {}).items()},
        "spacing": {str(i): "var(--space-%d)" % i for i in range(len(tokens.get("space", {}).get("scale", [])))},
        "borderRadius": {n: "var(--radius-%s)" % n for n in tokens.get("radius", {})},
        "boxShadow": {n: "var(--shadow-%s)" % n for n in tokens.get("shadow", {})},
    }
    return "// Generated by tokens.py. Use as: theme: { extend: require('./tailwind.tokens.js') }\n" \
           "module.exports = " + json.dumps(theme, indent=2) + ";\n"


def print_contrast(results):
    fails = 0
    for fg, bg, kind, r, status in results:
        if status != "ok":
            fails += 1
            need = NEED.get(kind, 4.5)
            got = "%.2f" % r if r is not None else "-"
            print("  %-5s %s on %s (%s): %s, needs %.1f" % (status, fg, bg, kind, got, need))
    print("contrast: %d pairs, %d failing" % (len(results), fails))
    return fails


def main(argv=None):
    ap = argparse.ArgumentParser(description="Design tokens to CSS, Tailwind, and a contrast check")
    ap.add_argument("cmd", choices=["css", "tailwind", "contrast", "all"])
    ap.add_argument("tokens")
    ap.add_argument("--out", default=".", help="folder for tokens.css and tailwind.tokens.js")
    args = ap.parse_args(argv)
    with open(args.tokens, encoding="utf-8") as f:
        tokens = json.load(f)

    if args.cmd == "contrast":
        return 1 if print_contrast(contrast(tokens)) else 0
    if args.cmd in ("css", "all"):
        os.makedirs(args.out, exist_ok=True)
        with open(os.path.join(args.out, "tokens.css"), "w", encoding="utf-8") as f:
            f.write(to_css(tokens))
        print("-> %s" % os.path.join(args.out, "tokens.css"))
    if args.cmd in ("tailwind", "all"):
        os.makedirs(args.out, exist_ok=True)
        with open(os.path.join(args.out, "tailwind.tokens.js"), "w", encoding="utf-8") as f:
            f.write(to_tailwind(tokens))
        print("-> %s" % os.path.join(args.out, "tailwind.tokens.js"))
    if args.cmd == "all":
        return 1 if print_contrast(contrast(tokens)) else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
